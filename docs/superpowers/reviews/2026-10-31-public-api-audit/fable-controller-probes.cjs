const assert = require('node:assert/strict');
const c = require('../../../../dist');
const source={hydration:'resolver',roots:()=>[{vertexId:0}],resolveVertex:id=>({kind:'found',data:id}),outgoing:v=>v.vertexId===0?[1,2].map(vertexId=>({target:{vertexId},data:'edge'})):[]};
const walk=new c.GraphWalk({source,limits:{maxAdmittedTargets:1,maxCandidateReadAttempts:10}});
const limited=[...walk.createRunner().iterateEvents()].filter(e=>e.kind==='vertex');
assert.equal(limited.length,1);
walk.configure({limits:{maxDepth:1}});
const events=[...walk.createRunner().iterateEvents({emitEvents:['vertex','edge']})];
assert.equal(events.filter(e=>e.kind==='vertex').length,3);
const edge=events.find(e=>e.kind==='edge');assert.equal(edge.source.vertexId,0);assert.notEqual(edge.source,source);
console.log('limits replacement: tuning maxDepth dropped prior admission/read limits, observed vertices 1 -> 3');
console.log('walking edge source is a vertex, not the source adapter');
const found=(id,hints=[])=>({kind:'found',vertex:{vertexId:id,vertexContent:{$data:id,$childHints:hints}}});
const dagSource={resolveRoot:()=>found('root',['skip','child']),resolveChild:id=>id==='skip'?{kind:'omitted',vertexId:'skip',satisfiesDependencies:true}:found(id)};
const prepared=c.prepareDag({traversableGraph:dagSource});assert.equal(prepared.kind,'valid');
assert.deepEqual(prepared.dag.definition.omittedIds,['skip']);
assert.equal(prepared.dag.definition.vertices[0].slots.length,2);
assert.deepEqual(prepared.dag.vertices[0].children,['child']);
console.log('prepared projection drops omitted slot; faithful definition retains slot and omittedIds');
const runner=new c.DagTraversal({traversableGraph:dagSource}).createRunner().run();
const view=runner.getResolvedGraphView();
const foreign=new c.MutableRef(new c.Vertex({$data:'foreign',$childHints:[]}));
assert.equal(view.getChildrenOf(foreign),null);assert.throws(()=>view.getPathsTo(foreign),/Unknown vertex reference/);assert.throws(()=>view.getVertexId(foreign),/Unknown vertex reference/);
console.log('unknown graph handle: getChildrenOf -> null, getPathsTo/getVertexId -> Error');
const snapshot=runner.inspectMilestones();
assert.equal(snapshot.explain({vertexId:'unknown',milestone:'work'}).kind,'unknown');
const omitted=snapshot.explain({vertexId:'skip',milestone:'work'});assert.equal(omitted.kind,'known');assert.equal(omitted.progress,null);
console.log('milestone explanation: missing identity -> unknown; omitted identity -> known with null progress');
const error=new c.DagTraversalStallError({dependencies:[{id:'task',unmet:['p']}],unknownPrerequisiteIds:['p'],dependencyCycleComponents:[],dependencyBlockedIds:[],structurallyIncompleteIds:[]});
assert.deepEqual(error.diagnostics.dependencies[0],{id:'task',unmet:['p']});
console.log('stall dependency diagnostics use id/unmet rather than vertexId/unmetPrerequisiteIds');
