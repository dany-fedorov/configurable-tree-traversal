const assert = require('node:assert/strict');
const c = require('../../../../dist');
const found = (data, hints) => ({kind:'found', vertex:{vertexContent:{$data:data,$childHints:hints}}});
const omittedRunner = new c.DepthFirstTreeTraversal({traversableTree:{resolveRoot:()=>found('root',['omitted']),resolveChild:()=>({kind:'omitted'})}}).createRunner().run();
const omittedView=omittedRunner.getResolvedTreeView(); const omittedRoot=omittedView.getRoot();
assert.equal(omittedView.getChildrenOf(omittedRoot).length,0);
assert.equal(omittedRunner.isTraversalLeaf(omittedRoot),false);
console.log('all-omitted root: resolvedChildren=0, isTraversalLeaf=false');
const skippedRunner=new c.DepthFirstTreeTraversal({traversableTree:{resolveRoot:()=>found('root',['a','b']),resolveChild:h=>found(h,[])},inOrder:{afterChildIndices:{indices:[0]},visitSingleChildParent:true},visitors:{IN_ORDER:(v,ctx)=>ctx.isTreeRoot?{commands:[{commandName:c.TraversalVisitorCommandName.SKIP_REMAINING_CHILDREN}]}:undefined}}).createRunner().run();
const skippedView=skippedRunner.getResolvedTreeView(); const skippedRoot=skippedView.getRoot();
assert.equal(skippedView.getChildrenOf(skippedRoot).length,1);
assert.equal(skippedRunner.isTraversalLeaf(skippedRoot),true);
console.log('root skipped after first child: resolvedChildren=1, isTraversalLeaf=true');
const input=c.materializeDagInputFromRecords(['task'],{id:x=>x});
const runner=new c.DagTraversal({...input,workCompletion:'externalSettlement'}).createRunner();
const first=c.createDagWorkSession(runner), second=c.createDagWorkSession(runner);
const ticket=first.advance().workTickets[0]; const other=second.advance().workTickets[0];
assert.throws(()=>second.completeWork(ticket),TypeError);
assert.equal(second.completeWork(other).kind,'accepted');
assert.equal(first.completeWork(ticket).kind,'alreadyAccepted');
console.log('two wrapped sessions: tickets local, work progress shared');
const prepared=c.prepareDag(input); assert.equal(prepared.kind,'valid');
const independentA=prepared.dag.createWorkSession(), independentB=prepared.dag.createWorkSession();
independentA.completeWork(independentA.advance().workTickets[0]);
assert.equal(independentB.advance().kind,'awaitingSettlement');
console.log('two prepared-DAG sessions: work progress independent');
const rebuilt=c.rewriteObject({a:1},{rewrite:()=>({kind:'keep'})}).getOutput();
assert.deepEqual(rebuilt,{a:1});
console.log('keep preserves property semantics, but assembly may create a new composite value');
